-- View: Active Credit Back Rules with Bracket Count
CREATE OR REPLACE VIEW SALR_E_V_ACTIVE_RULES AS
SELECT
  r.RULE_ID,
  r.RULE_NAME,
  r.VALID_FROM,
  r.VALID_TO,
  r.MODE_CODE,
  r.IS_ACTIVE,
  COUNT(b.BRACKET_ID) AS BRACKET_COUNT,
  r.CREATED_AT,
  r.UPDATED_AT
FROM SALR_E_CREDIT_BACK_RULE r
LEFT JOIN SALR_E_CREDIT_BACK_RULE_BRACKET b ON r.RULE_ID = b.RULE_ID
WHERE r.IS_ACTIVE = 'Y'
  AND r.VALID_TO >= SYSDATE
GROUP BY r.RULE_ID, r.RULE_NAME, r.VALID_FROM, r.VALID_TO, r.MODE_CODE, r.IS_ACTIVE, r.CREATED_AT, r.UPDATED_AT;

-- View: Reseller Credit Balance Summary
CREATE OR REPLACE VIEW SALR_E_V_RESELLER_CREDIT_BALANCE AS
SELECT
  RESELLER_ID,
  SUM(CASE WHEN STATUS_CODE = 'EARNED' THEN CREDIT_AMOUNT ELSE 0 END) AS TOTAL_EARNED,
  SUM(CASE WHEN STATUS_CODE = 'REDEEMED' THEN CREDIT_AMOUNT ELSE 0 END) AS TOTAL_REDEEMED,
  SUM(CASE WHEN STATUS_CODE = 'EXPIRED' THEN CREDIT_AMOUNT ELSE 0 END) AS TOTAL_EXPIRED,
  SUM(CASE WHEN STATUS_CODE = 'EARNED' THEN CREDIT_AMOUNT ELSE 0 END)
    - SUM(CASE WHEN STATUS_CODE = 'REDEEMED' THEN CREDIT_AMOUNT ELSE 0 END) AS AVAILABLE_BALANCE,
  MAX(EARNED_AT) AS LAST_EARNED_DATE
FROM SALR_E_CREDIT_BACK_LEDGER
GROUP BY RESELLER_ID;

-- View: Promotion Performance Summary
CREATE OR REPLACE VIEW SALR_E_V_PROMO_PERFORMANCE AS
SELECT
  p.PROMO_ID,
  p.PROMO_NAME,
  p.START_DT,
  p.END_DT,
  p.STATUS_CODE,
  COUNT(DISTINCT ps.PROMO_SKU_ID) AS SKU_COUNT,
  COUNT(DISTINCT wm.RESELLER_ID) AS RESELLER_COUNT,
  SUM(CASE WHEN wm.STATUS_CODE = 'SENT' THEN 1 ELSE 0 END) AS SENT_COUNT,
  SUM(CASE WHEN wm.STATUS_CODE = 'DELIVERED' THEN 1 ELSE 0 END) AS DELIVERED_COUNT,
  SUM(CASE WHEN wm.STATUS_CODE = 'READ' THEN 1 ELSE 0 END) AS READ_COUNT,
  SUM(CASE WHEN wm.STATUS_CODE = 'REPLIED' THEN 1 ELSE 0 END) AS REPLIED_COUNT
FROM SALR_E_PROMO p
LEFT JOIN SALR_E_PROMO_SKU ps ON p.PROMO_ID = ps.PROMO_ID
LEFT JOIN SALR_E_WHATSAPP_MESSAGE wm ON p.PROMO_ID = wm.PROMO_ID AND wm.DIRECTION_CODE = 'OUTBOUND'
GROUP BY p.PROMO_ID, p.PROMO_NAME, p.START_DT, p.END_DT, p.STATUS_CODE;

