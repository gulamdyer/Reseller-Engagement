-- ----------------------------------------------------------------------------
-- 1. CREDIT BACK RULES & BRACKETS
-- ----------------------------------------------------------------------------

-- Credit Back Rule Master Table
CREATE TABLE SALR_E_CREDIT_BACK_RULE (
  RULE_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RULE_NAME          VARCHAR2(200) NOT NULL,
  VALID_FROM         DATE NOT NULL,
  VALID_TO           DATE NOT NULL,
  MODE_CODE          VARCHAR2(20) NOT NULL, -- 'NEXT_ORDER', 'NEXT_WITHIN', 'ANYTIME'
  IS_ACTIVE          CHAR(1) DEFAULT 'Y' CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY         VARCHAR2(100),
  CREATED_AT         DATE DEFAULT SYSDATE,
  UPDATED_BY         VARCHAR2(100),
  UPDATED_AT         DATE,
  CONSTRAINT SALR_E_CBR_MODE_CHK CHECK (MODE_CODE IN ('NEXT_ORDER', 'NEXT_WITHIN', 'ANYTIME'))
);

-- Create index on active rules for faster lookups
CREATE INDEX SALR_E_CBR_ACTIVE_IDX ON SALR_E_CREDIT_BACK_RULE (IS_ACTIVE, VALID_FROM, VALID_TO);

COMMENT ON TABLE SALR_E_CREDIT_BACK_RULE IS 'Master table for Credit Back rules with validity periods and modes';
COMMENT ON COLUMN SALR_E_CREDIT_BACK_RULE.MODE_CODE IS 'Application mode: NEXT_ORDER (next order only), NEXT_WITHIN (next order within timeframe), ANYTIME (any order in window)';

-- Credit Back Rule Brackets - defines percentage tiers per rule
CREATE TABLE SALR_E_CREDIT_BACK_RULE_BRACKET (
  BRACKET_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RULE_ID            NUMBER NOT NULL REFERENCES SALR_E_CREDIT_BACK_RULE (RULE_ID) ON DELETE CASCADE,
  MIN_SALES_AMOUNT   NUMBER(18,2) NOT NULL,
  MAX_SALES_AMOUNT   NUMBER(18,2), -- NULL means "no upper limit"
  CREDIT_PERCENT     NUMBER(5,2) NOT NULL,
  PRIORITY_NO        NUMBER(5) DEFAULT 1,
  CONSTRAINT SALR_E_CB_BRK_UK UNIQUE (RULE_ID, MIN_SALES_AMOUNT),
  CONSTRAINT SALR_E_CB_BRK_AMOUNT_CHK CHECK (MAX_SALES_AMOUNT IS NULL OR MAX_SALES_AMOUNT > MIN_SALES_AMOUNT),
  CONSTRAINT SALR_E_CB_BRK_PERCENT_CHK CHECK (CREDIT_PERCENT >= 0 AND CREDIT_PERCENT <= 100)
);

CREATE INDEX SALR_E_CBB_RULE_IDX ON SALR_E_CREDIT_BACK_RULE_BRACKET (RULE_ID);

COMMENT ON TABLE SALR_E_CREDIT_BACK_RULE_BRACKET IS 'Defines percentage brackets for each Credit Back rule (e.g., 0-5000=1%, 5000-10000=2%)';

-- ----------------------------------------------------------------------------
-- 2. CREDIT BACK LEDGER
-- ----------------------------------------------------------------------------

-- Credit Back Ledger - tracks earned, redeemed, and expired credits
CREATE TABLE SALR_E_CREDIT_BACK_LEDGER (
  LEDGER_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RESELLER_ID        NUMBER NOT NULL, -- references ERP reseller master (SPINE_RESELLER)
  ORDER_ID           NUMBER,         -- references ERP order/invoice (SPINE_SALES_ORDER or SPINE_INVOICE)
  RULE_ID            NUMBER REFERENCES SALR_E_CREDIT_BACK_RULE (RULE_ID),
  PROMO_ID           NUMBER,         -- optional: link to SALR_E_PROMO
  CREDIT_AMOUNT      NUMBER(18,2) NOT NULL,
  STATUS_CODE        VARCHAR2(20) NOT NULL, -- 'EARNED','REDEEMED','EXPIRED'
  EARNED_AT          DATE DEFAULT SYSDATE,
  REDEEMED_AT        DATE,
  EXPIRY_DATE        DATE,
  REMARKS            VARCHAR2(500),
  CREATED_AT         DATE DEFAULT SYSDATE,
  CREATED_BY         VARCHAR2(100),
  CONSTRAINT SALR_E_CBL_STATUS_CHK CHECK (STATUS_CODE IN ('EARNED','REDEEMED','EXPIRED'))
);

CREATE INDEX SALR_E_CBL_RESELLER_IDX ON SALR_E_CREDIT_BACK_LEDGER (RESELLER_ID, STATUS_CODE);
CREATE INDEX SALR_E_CBL_ORDER_IDX ON SALR_E_CREDIT_BACK_LEDGER (ORDER_ID);
CREATE INDEX SALR_E_CBL_STATUS_IDX ON SALR_E_CREDIT_BACK_LEDGER (STATUS_CODE, EXPIRY_DATE);

COMMENT ON TABLE SALR_E_CREDIT_BACK_LEDGER IS 'Ledger of all Credit Back transactions - earned, redeemed, and expired';
COMMENT ON COLUMN SALR_E_CREDIT_BACK_LEDGER.STATUS_CODE IS 'EARNED (available), REDEEMED (used), EXPIRED (no longer valid)';

-- ----------------------------------------------------------------------------
-- 3. PROMOTIONS & PROMO SKUs
-- ----------------------------------------------------------------------------

-- Promotions Master Table
CREATE TABLE SALR_E_PROMO (
  PROMO_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROMO_NAME         VARCHAR2(200) NOT NULL,
  DESCRIPTION        VARCHAR2(1000),
  START_DT           DATE NOT NULL,
  END_DT             DATE NOT NULL,
  TARGET_SEGMENT     VARCHAR2(50), -- e.g. 'DORMANT','ACTIVE','ALL'
  STATUS_CODE        VARCHAR2(20) DEFAULT 'DRAFT', -- 'DRAFT','ACTIVE','EXPIRED','CANCELLED'
  CREATED_BY         VARCHAR2(100),
  CREATED_AT         DATE DEFAULT SYSDATE,
  UPDATED_BY         VARCHAR2(100),
  UPDATED_AT         DATE,
  CONSTRAINT SALR_E_PROMO_DATE_CHK CHECK (END_DT >= START_DT),
  CONSTRAINT SALR_E_PROMO_STATUS_CHK CHECK (STATUS_CODE IN ('DRAFT','ACTIVE','EXPIRED','CANCELLED'))
);

CREATE INDEX SALR_E_PROMO_STATUS_IDX ON SALR_E_PROMO (STATUS_CODE, START_DT, END_DT);
CREATE INDEX SALR_E_PROMO_SEGMENT_IDX ON SALR_E_PROMO (TARGET_SEGMENT);

COMMENT ON TABLE SALR_E_PROMO IS 'Master table for promotional campaigns';
COMMENT ON COLUMN SALR_E_PROMO.TARGET_SEGMENT IS 'Target reseller segment: DORMANT (inactive), ACTIVE, ALL';

-- Promotion SKU Details - links SKUs to promotions with pricing
CREATE TABLE SALR_E_PROMO_SKU (
  PROMO_SKU_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROMO_ID           NUMBER NOT NULL REFERENCES SALR_E_PROMO (PROMO_ID) ON DELETE CASCADE,
  SKU_ID             NUMBER NOT NULL, -- ERP SKU ID (references SPINE_SKU)
  SKU_CODE           VARCHAR2(100),   -- denormalized for quick access
  SKU_NAME           VARCHAR2(500),   -- denormalized for quick access
  BEFORE_PRICE       NUMBER(18,4),
  OFFER_PRICE        NUMBER(18,4),
  DISCOUNT_PERCENT   NUMBER(5,2),     -- calculated: (BEFORE_PRICE - OFFER_PRICE) / BEFORE_PRICE * 100
  ASSET_URL          VARCHAR2(500),   -- image file/url placeholder for offer card
  CAPTION_EN         CLOB,            -- English WhatsApp caption
  CAPTION_AR         CLOB,            -- Arabic WhatsApp caption
  CREATED_AT         DATE DEFAULT SYSDATE
);

CREATE INDEX SALR_E_PROMO_SKU_PROMO_IDX ON SALR_E_PROMO_SKU (PROMO_ID);
CREATE INDEX SALR_E_PROMO_SKU_SKU_IDX ON SALR_E_PROMO_SKU (SKU_ID);

COMMENT ON TABLE SALR_E_PROMO_SKU IS 'SKU-level details for each promotion including pricing and WhatsApp templates';

-- ----------------------------------------------------------------------------
-- 4. WHATSAPP MESSAGE LOGS
-- ----------------------------------------------------------------------------

-- WhatsApp Message Log - all inbound, outbound, and internal alert messages
CREATE TABLE SALR_E_WHATSAPP_MESSAGE (
  MSG_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RESELLER_ID        NUMBER,         -- NULL for internal alerts
  PROMO_ID           NUMBER REFERENCES SALR_E_PROMO (PROMO_ID),
  DIRECTION_CODE     VARCHAR2(20) NOT NULL, -- 'OUTBOUND','INBOUND','INTERNAL_ALERT'
  MESSAGE_TYPE       VARCHAR2(50), -- 'PROMO','AVAILABILITY','ORDER','CREDIT','PROFILE','INTERNAL_ALERT','OTHER'
  TEMPLATE_ID        VARCHAR2(100),
  PHONE_NUMBER       VARCHAR2(30),   -- WhatsApp phone number (E.164 format recommended)
  MESSAGE_BODY       CLOB,           -- actual message content
  STATUS_CODE        VARCHAR2(20), -- 'QUEUED','SENT','DELIVERED','READ','REPLIED','FAILED'
  SOURCE_CHANNEL     VARCHAR2(50), -- 'WHATSAPP_API','SIMULATION','MANUAL'
  SENT_AT            DATE,
  DELIVERED_AT       DATE,
  READ_AT            DATE,
  REPLIED_AT         DATE,
  FAILED_AT          DATE,
  ERROR_MESSAGE      VARCHAR2(1000),
  EXTERNAL_MSG_ID    VARCHAR2(200), -- WhatsApp API message ID
  RAW_PAYLOAD        CLOB,           -- raw JSON payload from/to WhatsApp API
  CREATED_AT         DATE DEFAULT SYSDATE,
  CONSTRAINT SALR_E_WM_DIR_CHK CHECK (DIRECTION_CODE IN ('OUTBOUND','INBOUND','INTERNAL_ALERT')),
  CONSTRAINT SALR_E_WM_STATUS_CHK CHECK (STATUS_CODE IN ('QUEUED','SENT','DELIVERED','READ','REPLIED','FAILED'))
);

CREATE INDEX SALR_E_WM_RESELLER_IDX ON SALR_E_WHATSAPP_MESSAGE (RESELLER_ID, CREATED_AT DESC);
CREATE INDEX SALR_E_WM_PROMO_IDX ON SALR_E_WHATSAPP_MESSAGE (PROMO_ID);
CREATE INDEX SALR_E_WM_DIRECTION_IDX ON SALR_E_WHATSAPP_MESSAGE (DIRECTION_CODE, STATUS_CODE);
CREATE INDEX SALR_E_WM_STATUS_IDX ON SALR_E_WHATSAPP_MESSAGE (STATUS_CODE, CREATED_AT DESC);

COMMENT ON TABLE SALR_E_WHATSAPP_MESSAGE IS 'Complete log of all WhatsApp messages: outbound promos, inbound queries, internal alerts';
COMMENT ON COLUMN SALR_E_WHATSAPP_MESSAGE.DIRECTION_CODE IS 'OUTBOUND (to reseller), INBOUND (from reseller), INTERNAL_ALERT (to Sedar team)';

